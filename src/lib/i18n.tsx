export type TKey = keyof typeof D;
const IDX: Record<Lang, number> = { ru: 0, en: 1, uz: 2, tj: 3 };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string };
const I18n = createContext<Ctx>({ lang: "ru", setLang: () => {}, t: (k) => D[k][0]! });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangS] = useState<Lang>("ru");
  useEffect(() => {
    const s = localStorage.getItem("lang") as Lang | null;
    if (s && s in IDX) setLangS(s);
  }, []);
  const setLang = (l: Lang) => { setLangS(l); localStorage.setItem("lang", l); };
  return <I18n.Provider value={{ lang, setLang, t: (k) => D[k][IDX[lang]] ?? D[k][0]! }}>{children}</I18n.Provider>;
}
export const useT = () => useContext(I18n);
